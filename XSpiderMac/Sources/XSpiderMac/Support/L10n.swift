/// 重复 key 安全的字典构建（后值覆盖前值，不会 trap）
private func safeDict(_ pairs: [(String, String)]) -> [String: String] {
    var dict: [String: String] = [:]
    for (k, v) in pairs { dict[k] = v }
    return dict
}

